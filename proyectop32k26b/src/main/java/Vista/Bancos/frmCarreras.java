    // ── Carga la tabla ───────────────────────────────────────────
    private void cargarTabla() {
        DefaultTableModel modelo = new DefaultTableModel(
            new String[]{"ID", "Nombre de la Carrera", "Código de la Facultad", "Estatus de la Carrera"}, 0
        ) {
            @Override public boolean isCellEditable(int r, int c) { return false; }
        };

        for (clsCarreras c : carrerasDAO.listar()) {
            modelo.addRow(new Object[]{
                c.getCodigo_carrera(),
                c.getNombre_carrera(),
                c.getCodigo_facultad(),
                c.getEstatus_carrera()
            });
        }
        Tabla.setModel(modelo);
    }

    // ── Clic en fila → llena campos ──────────────────────────────
    private void configurarSeleccionTabla() {
        Tabla.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && Tabla.getSelectedRow() != -1) {
                int fila = Tabla.getSelectedRow();
                txtbuscado.setText(Tabla.getValueAt(fila, 0).toString());
                jTextField1.setText(Tabla.getValueAt(fila, 1).toString());
                jTextField2.setText(Tabla.getValueAt(fila, 2).toString());
                jTextField3.setText(Tabla.getValueAt(fila, 3).toString());
            }
        });
    }

    // ── Valida campos obligatorios ───────────────────────────────
    private boolean camposCompletos() {
        if (txtbuscado.getText().trim().isEmpty() ||
            jTextField1.getText().trim().isEmpty() ||
            jTextField2.getText().trim().isEmpty() ||
            jTextField3.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Complete todos los campos: Código, Nombre, Código Facultad y Estatus.",
                "Campos incompletos", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }

    // ── Construye objeto desde formulario ────────────────────────
    private clsCarreras getObjetoDeFormulario() {
        clsCarreras c = new clsCarreras();
        c.setCodigo_carrera(txtbuscado.getText().trim());
        c.setNombre_carrera(jTextField1.getText().trim());
        c.setCodigo_facultad(jTextField2.getText().trim());
        c.setEstatus_carrera(jTextField3.getText().trim());
        return c;
    }

    // ── Limpia todos los campos ──────────────────────────────────
    private void limpiarCampos() {
        txtbuscado.setText("");
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        Tabla.clearSelection();
    }

