    private void eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_eliminarActionPerformed
         if (txtbuscado.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione una carrera para eliminar.", "Atención",
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "¿Está seguro de eliminar esta carrera?",
            "Confirmar eliminación", javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirm != javax.swing.JOptionPane.YES_OPTION) return;
        try {
            String codigo = txtbuscado.getText().trim();
            carrerasDAO.delete(codigo);
            javax.swing.JOptionPane.showMessageDialog(this,
                "Carrera eliminada correctamente.", "Éxito",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
            frmBitacoraBancaria.registrarBitacora(
                "DELETE", "Carreras", null,
                "Código: " + txtbuscado.getText().trim() +
                " | Nombre: " + jTextField1.getText().trim(),
                null, "Carrera eliminada");
            cargarTabla();
            limpiarCampos();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Error al eliminar: " + e.getMessage(), "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_eliminarActionPerformed

    private void LimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LimpiarActionPerformed
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "¿Está seguro de ELIMINAR TODOS los registros?\nEsta acción no se puede deshacer.",
            "Confirmar limpieza total",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE);
        if (confirm != javax.swing.JOptionPane.YES_OPTION) return;
        try {
            carrerasDAO.deleteAll();
            frmBitacoraBancaria.registrarBitacora(
                "DELETE ALL", "Carreras", null, null, null,
                "Se eliminaron todos los registros de la tabla Carreras");
            javax.swing.JOptionPane.showMessageDialog(this,
                "Todos los registros fueron eliminados.", "Éxito",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
            cargarTabla();
            limpiarCampos();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Error al limpiar: " + e.getMessage(), "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_LimpiarActionPerformed

    private void actualizaarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_actualizaarActionPerformed
         if (txtbuscado.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione una carrera para actualizar.", "Atención",
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!camposCompletos()) return;
        try {
            clsCarreras c = getObjetoDeFormulario();
            carrerasDAO.update(c);
            javax.swing.JOptionPane.showMessageDialog(this,
                "Carrera actualizada correctamente.", "Éxito",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
            frmBitacoraBancaria.registrarBitacora(
                "UPDATE", "Carreras", null, null,
                "Código: " + txtbuscado.getText().trim() +
                " | Nombre: " + jTextField1.getText().trim() +
                " | Facultad: " + jTextField2.getText().trim() +
                " | Estatus: " + jTextField3.getText().trim(),
                "Carrera actualizada");
            cargarTabla();
            limpiarCampos();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Error al actualizar: " + e.getMessage(), "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_actualizaarActionPerformed

    private void buscar2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscar2ActionPerformed
      if (txtbuscado.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Ingrese un código para buscar.", "Atención",
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            clsCarreras c = carrerasDAO.query(txtbuscado.getText().trim());
            if (c != null) {
                jTextField1.setText(c.getNombre_carrera());
                jTextField2.setText(c.getCodigo_facultad());
                jTextField3.setText(c.getEstatus_carrera());
                frmBitacoraBancaria.registrarBitacora(
                    "SELECT", "Carreras", null, null, null,
                    "Consulta de carrera por código: " + txtbuscado.getText().trim());
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "No se encontró carrera con código: " + txtbuscado.getText().trim(),
                    "Sin resultados", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                limpiarCampos();
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Error al buscar: " + e.getMessage(), "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_buscar2ActionPerformed

    private void reporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_reporteActionPerformed
       java.sql.Connection conn = null;
    try {
        conn = Modelo.Conexion.getConnection();
        
        
        String ruta = new java.io.File("").getAbsolutePath() 
                    + "\\src\\main\\java\\Reportes\\Bancos\\RCarreas.jrxml";
        
        System.out.println("Buscando reporte en: " + ruta); // Para verificar en consola
        
        java.io.File archivo = new java.io.File(ruta);
        if (!archivo.exists()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "No se encontró el archivo del reporte en:\n" + ruta,
                "Archivo no encontrado", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        java.util.Map<String, Object> parametros = new java.util.HashMap<>();
        
        net.sf.jasperreports.engine.JasperReport reporte =
            net.sf.jasperreports.engine.JasperCompileManager.compileReport(ruta);
        
        net.sf.jasperreports.engine.JasperPrint print =
          net.sf.jasperreports.engine.JasperFillManager.fillReport(reporte, parametros, conn);
        
        net.sf.jasperreports.engine.JasperExportManager.exportReportToPdfFile(print,"reporte.pdf");
        net.sf.jasperreports.swing.JRViewer viewer = new net.sf.jasperreports.swing.JRViewer(print);
        
        javax.swing.JFrame frame = new javax.swing.JFrame("Reporte de Clientes");
        frame.setSize(800, 600);
        frame.setLocationRelativeTo(null);
        frame.setDefaultCloseOperation(javax.swing.JFrame.DISPOSE_ON_CLOSE);
        frame.add(viewer);
        frame.setVisible(true);
        
    } catch (Exception e) {
        e.printStackTrace();
        javax.swing.JOptionPane.showMessageDialog(this,
            "Error al generar el reporte:\n" + e.getMessage(),
            "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    } finally {
        if (conn != null) {
            try { conn.close(); } catch (Exception ex) { ex.printStackTrace(); }
        }
    }
    }//GEN-LAST:event_reporteActionPerformed

